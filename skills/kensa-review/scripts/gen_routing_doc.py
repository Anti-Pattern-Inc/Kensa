#!/usr/bin/env python3
"""Maintainers: regenerate references/evidence-routing.md from assets/routing.json + assets/cards.json + a checklist CSV.

  python3 scripts/gen_routing_doc.py CHECKLIST.csv > references/evidence-routing.md

The document is English (the default language of the bundled cards, whose titles it lists).
"""
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import kensa  # noqa: E402

LETTER = {"aws": "A", "repo": "R", "interview": "I"}


def route_of(routing, it):
    r = routing["choices"].get(it["choice_id"])
    if r is not None:
        return r
    q = routing["questions"].get(it["question_id"], routing["fallback"])
    return {"ch": q["ch"], "areas": q["areas"], "draft": bool(q.get("draft")), "card": None}


def code(r):
    return "".join(LETTER[c] for c in r["ch"]) + ("*" if r.get("draft") else "")


def render(n_questions, n_items, tiers, prim, pillar_tables, card_rows):
    """The markdown text. pillar_tables: {pillar: [(question_id, items, routes, cards), ...]} (routes / cards already formatted);
    card_rows: [(card_id, title, items_covered, effort, priority), ...]."""
    out = []
    P = out.append
    P("# Evidence routing\n")
    P(f"How each of the {n_questions} questions and {n_items} best practices is filled in, by route.")
    P("**A = AWS (live environment, read-only) / R = repository (IaC, documents, GitHub settings and activity, CI) / I = interview (decision cards)**. "
      "The first letter is the primary route; if the primary route cannot settle an item, the next route is tried. "
      "A trailing `*` marks a **draft** route (the evidence can only show that something exists, and a person confirms it; absence is not grounds for a verdict).")
    P("The source of truth is `assets/routing.json` (per-QuestionId defaults plus per-ChoiceId overrides). "
      "A ChoiceId that is unknown (another lens, or an update) falls back to its QuestionId default, and failing that to interview. "
      "Classify it with `route-unknown` / `route-apply`, which registers it in `.kensa/routing.local.json`.")
    P("This document is generated by `scripts/gen_routing_doc.py`.\n")
    P("`areas` is the join key to the AWS / repository checks (`aws-readonly-checks.md` / `repo-signals.md`). Use it as in `items --area kms`.\n")
    P(f"## Summary (all {n_items} items)\n")
    P("| Route | Count | Meaning |\n|---|---|---|")
    P(f"| Decided | {tiers['decide']} | Can be decided from AWS / repository evidence (encryption, network, logging/detection, CI, etc.) |")
    P(f"| Draft | {tiers['draft']} | Evidence only shows that something exists. It is pre-filled on the decision card and a person confirms it (post-mortems, runbooks, escalation, threat models, DR, game days, etc.) |")
    P(f"| Interview only | {tiers['ask']} | Only a person can answer (culture, priorities, management involvement, etc.) |")
    P(f"\nItems reachable with evidence (decided + draft): {tiers['decide'] + tiers['draft']} / {n_items}\n")
    P("Primary-route breakdown: " + ", ".join(f"{LETTER[k]}={v}" for k, v in sorted(prim.items())) + "\n")
    P("Note: this classification is a design decision of this project, not an AWS classification. If no evidence can be obtained, the item falls back to interview.\n")
    P("## Routes per question\n")
    for p in kensa.PILLAR_ORDER:
        if p not in pillar_tables:
            continue
        P(f"### {p}\n")
        P("| QuestionId | Items | Routes (count) | Interview cards |\n|---|---|---|---|")
        for qid, n, routes, cards in pillar_tables[p]:
            P(f"| `{qid}` | {n} | {routes} | {cards} |")
        P("")
    P("## Decision cards\n")
    P("| CardId | Theme | Items covered | Effort | Priority |\n|---|---|---|---|---|")
    for cid, title, n, effort, priority in card_rows:
        P(f"| `{cid}` | {title} | {n} | {effort} | {priority} |")
    return "\n".join(out)


def main(csv_path):
    routing = kensa.assets("routing.json")
    cards = kensa.assets("cards.json")
    rows = kensa.parse_checklist_csv(csv_path)
    items = [dict(r, route=route_of(routing, r)) for r in rows]
    tiers = collections.Counter(kensa.tier(i) for i in items)
    prim = collections.Counter(i["route"]["ch"][0] for i in items)
    byp = collections.OrderedDict()
    for i in items:
        byp.setdefault(i["pillar"], collections.OrderedDict()).setdefault(i["question_id"], []).append(i)
    pillar_tables = {}
    for p, qs in byp.items():
        table = []
        for qid, its in qs.items():
            c = collections.Counter(code(i["route"]) for i in its)
            cs = sorted({i["route"]["card"] for i in its if i["route"].get("card")})
            table.append((qid, len(its), ", ".join(f"{k}×{v}" for k, v in c.most_common()), ", ".join(cs) or "-"))
        pillar_tables[p] = table
    cover = collections.Counter(i["route"]["card"] for i in items if i["route"].get("card"))
    card_rows = [(c["id"], c["title"], cover.get(c["id"], 0), c["recommend"]["effort"], c["recommend"]["priority"]) for c in cards["cards"]]
    print(render(len({i["question_id"] for i in items}), len(items), tiers, prim, pillar_tables, card_rows))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
